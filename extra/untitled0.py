"""**ELO & MATCH PREDICTOR**"""

import math
import pandas as pd

class SoccerEloEngine:
    def __init__(self, k_factor=32, home_advantage=100, default_rating=1500):
        self.k_factor = k_factor
        self.home_advantage = home_advantage
        self.default_rating = default_rating
        self.ratings = {}

    def get_rating(self, team_name):
        return self.ratings.get(team_name, self.default_rating)

    def predict_match(self, home_team, away_team):
        """Calculates win/draw/loss probabilities for a match fixture."""
        r_home = self.get_rating(home_team) + self.home_advantage
        r_away = self.get_rating(away_team)

        # Expected score (Win probability scale)
        exp_home = 1 / (1 + 10 ** ((r_away - r_home) / 400))
        exp_away = 1 - exp_home

        # Simple draw model estimation based on rating difference closeness
        rating_diff = abs(r_home - r_away)
        draw_prob = max(0.15, 0.28 - (rating_diff / 2000))

        # Adjust home/away win probabilities around draw likelihood
        home_win_prob = exp_home * (1 - draw_prob)
        away_win_prob = exp_away * (1 - draw_prob)

        return {
            "home_win": round(home_win_prob * 100, 2),
            "draw": round(draw_prob * 100, 2),
            "away_win": round(away_win_prob * 100, 2)
        }

    def update_ratings(self, home_team, away_team, home_score, away_score):
        """Updates team ratings after a completed match."""
        r_home = self.get_rating(home_team)
        r_away = self.get_rating(away_team)

        # Actual outcome score: Win=1.0, Draw=0.5, Loss=0.0
        if home_score > away_score:
            actual_home, actual_away = 1.0, 0.0
        elif home_score == away_score:
            actual_home, actual_away = 0.5, 0.5
        else:
            actual_home, actual_away = 0.0, 1.0

        # Expected scores
        exp_home = 1 / (1 + 10 ** (((r_away) - (r_home + self.home_advantage)) / 400))
        exp_away = 1 - exp_home

        # New ratings calculation
        new_r_home = r_home + self.k_factor * (actual_home - exp_home)
        new_r_away = r_away + self.k_factor * (actual_away - exp_away)

        self.ratings[home_team] = round(new_r_home, 1)
        self.ratings[away_team] = round(new_r_away, 1)

