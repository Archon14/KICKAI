class ExpectedGoalsModel:
    """
    Logistic Regression model for calculating shot xG based on geometric features.
    """
    def __init__(self):
        # Trained feature coefficients [Distance to Goal Center, Shot Angle (rad), Defender Density]
        self.coef = np.array([-0.115, 0.782, -0.240])
        self.intercept = -0.450

    def compute_xg(self, distance, angle_radians, defender_density):
        features = np.array([distance, angle_radians, defender_density])
        logit = np.dot(features, self.coef) + self.intercept
        return 1.0 / (1.0 + np.exp(-logit))

class EloRatingSystem:
    """
    Match outcome rating updates using standard Elo formulations.
    """
    def __init__(self, k_factor=32.0):
        self.k_factor = k_factor

    def predict_prob(self, rating_a, rating_b):
        return 1.0 / (1.0 + 10.0 ** ((rating_b - rating_a) / 400.0))

    def update_ratings(self, rating_a, rating_b, score_a):
        # score_a: 1.0 for Win, 0.5 for Draw, 0.0 for Loss
        expected_a = self.predict_prob(rating_a, rating_b)
        new_rating_a = rating_a + self.k_factor * (score_a - expected_a)
        new_rating_b = rating_b + self.k_factor * ((1.0 - score_a) - (1.0 - expected_a))
        return new_rating_a, new_rating_b


