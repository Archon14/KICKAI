def draw_skeleton_on_frame(frame_path, stgcn_tensor, frame_idx=0, min_conf=0.2):
    """
    Overlays extracted keypoints and skeleton connections onto a match frame.
    """
    img = cv2.imread(frame_path)
    if img is None:
        print(f"Frame image not found at {frame_path}")
        return

    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    # stgcn_tensor shape: (C=3, T, V=17, M)
    num_players = stgcn_tensor.shape[3]

    for m in range(num_players):
        # Extract X, Y, and Confidence for the given frame_idx and player m
        x_coords = stgcn_tensor[0, frame_idx, :, m].numpy()
        y_coords = stgcn_tensor[1, frame_idx, :, m].numpy()
        confs = stgcn_tensor[2, frame_idx, :, m].numpy()

        # Plot joints (keypoint nodes)
        for v in range(17):
            if confs[v] > min_conf:
                cv2.circle(img_rgb, (int(x_coords[v]), int(y_coords[v])), 4, (0, 255, 0), -1)

        # Draw skeleton limb connections
        for start_j, end_j in SKELETON_CONNECTIONS:
            # Shift 1-based index to 0-based index
            s, e = start_j - 1, end_j - 1
            if confs[s] > min_conf and confs[e] > min_conf:
                pt1 = (int(x_coords[s]), int(y_coords[s]))
                pt2 = (int(x_coords[e]), int(y_coords[e]))
                cv2.line(img_rgb, pt1, pt2, (255, 0, 0), 2)

    plt.figure(figsize=(12, 8))
    plt.imshow(img_rgb)
    plt.axis("off")
    plt.title(f"ST-GCN Skeleton Keypoint Overlay (Frame {frame_idx})")
