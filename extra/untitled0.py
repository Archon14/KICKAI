# 4.1 CV SKILL MODEL: Spatial-Temporal Graph Convolution (ST-GCN Block)
# ------------------------------------------------------------------------------
class GraphConvBlock(nn.Module):
    """
    Spatial Graph Convolution layer implementing: Z = D^(-1/2) * A * D^(-1/2) * X * W
    """
    def __init__(self, in_channels, out_channels, num_nodes=17):
        super(GraphConvBlock, self).__init__()
        self.num_nodes = num_nodes
        # Trainable weight tensor W
        self.weight = nn.Parameter(torch.FloatTensor(in_channels, out_channels))
        # Learnable spatial adjacency matrix parameter initialized to identity + random edges
        self.A = nn.Parameter(torch.FloatTensor(num_nodes, num_nodes))
        self.reset_parameters()

    def reset_parameters(self):
        nn.init.kaiming_uniform_(self.weight)
        nn.init.eye_(self.A)

    def forward(self, x):
        # x shape: (N, C, T, V) where N=batch, C=channels, T=frames, V=vertices/joints
        N, C, T, V = x.size()

        # Compute normalized adjacency matrix: D^(-1/2) * A * D^(-1/2)
        A_sym = (self.A + self.A.T) / 2.0
        deg = torch.sum(torch.abs(A_sym), dim=1) + 1e-5
        deg_inv_sqrt = torch.diag(torch.pow(deg, -0.5))
        A_norm = torch.mm(torch.mm(deg_inv_sqrt, A_sym), deg_inv_sqrt)

        # Spatial Graph Convolution
        x_perm = x.permute(0, 2, 3, 1)  # (N, T, V, C)
        out = torch.matmul(x_perm, self.weight)  # (N, T, V, C_out)
        out = torch.matmul(A_norm, out.permute(0, 1, 3, 2).reshape(-1, V, C)).reshape(N, T, -1, V)
        return out.permute(0, 2, 1, 3)  # (N, C_out, T, V)

class STGCNSkillEvaluator(nn.Module):
    """
    ST-GCN Architecture for motor skill embedding extraction.
    Input Tensor Shape: (N, C, T, V) -> (Batch, 3, Frames, 17 COCO Keypoints)
    """
    def __init__(self, in_channels=3, embedding_dim=128, num_nodes=17):
        super(STGCNSkillEvaluator, self).__init__()
        self.gcn1 = GraphConvBlock(in_channels, 64, num_nodes)
        self.tcn1 = nn.Sequential(
            nn.Conv2d(64, 64, kernel_size=(9, 1), padding=(4, 0)),
            nn.BatchNorm2d(64),
            nn.ReLU()
        )
        self.gcn2 = GraphConvBlock(64, 128, num_nodes)
        self.tcn2 = nn.Sequential(
            nn.Conv2d(128, embedding_dim, kernel_size=(9, 1), padding=(4, 0)),
            nn.BatchNorm2d(embedding_dim),
            nn.ReLU()
        )
        self.global_pool = nn.AdaptiveAvgPool2d((1, 1))

    def forward(self, x):
        x = self.tcn1(self.gcn1(x))
        x = self.tcn2(self.gcn2(x))
        x = self.global_pool(x)  # (N, embedding_dim, 1, 1)
        return x.view(x.size(0), -1)  # Output feature vector embedding


