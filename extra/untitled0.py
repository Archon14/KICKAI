# 4. Keypoint extraction function
def extract_stgcn_keypoints(df, img_dir, model, seq_len=30):
    frames = sorted(df["frame"].unique())[:seq_len]
    unique_tracks = df[df["frame"].isin(frames)]["track_id"].unique()

    num_tracks = len(unique_tracks)
    track_to_idx = {track_id: idx for idx, track_id in enumerate(unique_tracks)}

    # Shape: (C=3, T=seq_len, V=17, M=num_tracks)
    skeleton_data = np.zeros((3, len(frames), 17, num_tracks), dtype=np.float32)

    for t_idx, frame_id in enumerate(frames):
        img_path = os.path.join(img_dir, f"{frame_id:06d}.jpg")
        if not os.path.exists(img_path):
            continue

        img = cv2.imread(img_path)
        frame_gt = df[df["frame"] == frame_id]

        for _, row in frame_gt.iterrows():
            m_idx = track_to_idx[row["track_id"]]
            x, y, w, h = int(row["left"]), int(row["top"]), int(row["width"]), int(row["height"])

            crop = img[max(0, y):max(0, y + h), max(0, x):max(0, x + w)]
            if crop.size == 0:
                continue

            results = model(crop, verbose=False)
            if results and results[0].keypoints is not None and len(results[0].keypoints.data) > 0:
                kp = results[0].keypoints.data[0].cpu().numpy()

                # Convert crop coordinates to global frame space
                kp[:, 0] += max(0, x)
                kp[:, 1] += max(0, y)

                skeleton_data[0, t_idx, :, m_idx] = kp[:, 0] # X
                skeleton_data[1, t_idx, :, m_idx] = kp[:, 1] # Y
                skeleton_data[2, t_idx, :, m_idx] = kp[:, 2] # Conf

    return torch.tensor(skeleton_data), unique_tracks

