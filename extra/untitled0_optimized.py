import pandas as pd

class SoccerEloEngine:
    def __init__(self, k_factor=32.0, home_advantage=100.0, default_rating=1500.0):
        self.k_factor = k_factor
        self.home_advantage = home_advantage
        self.default_rating = default_rating
        self.ratings = {}

    def get_rating(self, team):
        return self.ratings.get(team, self.default_rating)

    def predict_match(self, home_team, away_team):
        r_home = self.get_rating(home_team) + self.home_advantage
        r_away = self.get_rating(away_team)
        exp_home = 1.0 / (1.0 + 10.0 ** ((r_away - r_home) / 400.0))
        draw_prob = max(0.15, 0.28 - abs(r_home - r_away) / 2000.0)

        return {
            "home_win": round(exp_home * (1 - draw_prob) * 100, 2),
            "draw": round(draw_prob * 100, 2),
            "away_win": round((1 - exp_home) * (1 - draw_prob) * 100, 2),
        }

    def update_ratings(self, home_team, away_team, home_score, away_score):
        r_home = self.get_rating(home_team)
        r_away = self.get_rating(away_team)

        score_home = 1.0 if home_score > away_score else 0.5 if home_score == away_score else 0.0
        expected_home = 1.0 / (
            1.0 + 10.0 ** ((r_away - (r_home + self.home_advantage)) / 400.0)
        )

        delta = self.k_factor * (score_home - expected_home)
        self.ratings[home_team] = round(r_home + delta, 1)
        self.ratings[away_team] = round(r_away - delta, 1)

