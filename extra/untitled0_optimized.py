import numpy as np
import joblib
import torch
import torch.nn as nn

class GraphConvBlock(nn.Module):
    """Efficient learnable graph convolution for (N,C,T,V) tensors."""
    def __init__(self, in_channels, out_channels, num_nodes=17):
        super().__init__()
        self.weight = nn.Parameter(torch.empty(in_channels, out_channels))
        self.A = nn.Parameter(torch.eye(num_nodes))
        nn.init.kaiming_uniform_(self.weight, a=np.sqrt(5))

    def forward(self, x):
        # Normalize adjacency without constructing two dense diagonal matrices.
        A_sym = 0.5 * (self.A + self.A.transpose(0, 1))
        deg = A_sym.abs().sum(dim=1).clamp_min(1e-5)
        inv_sqrt = deg.rsqrt()
        A_norm = A_sym * inv_sqrt[:, None] * inv_sqrt[None, :]

        # x: N,C,T,V -> N,T,V,C
        x = x.permute(0, 2, 3, 1)
        x = torch.matmul(x, self.weight)       # N,T,V,Cout
        x = torch.einsum("vw,ntwc->ntvc", A_norm, x)
        return x.permute(0, 3, 1, 2).contiguous()

class STGCNSkillEvaluator(nn.Module):
    def __init__(self, in_channels=3, embedding_dim=128, num_nodes=17):
        super().__init__()
        self.gcn1 = GraphConvBlock(in_channels, 64, num_nodes)
        self.tcn1 = nn.Sequential(
            nn.Conv2d(64, 64, (9, 1), padding=(4, 0), bias=False),
            nn.BatchNorm2d(64),
            nn.ReLU(inplace=True),
        )
        self.gcn2 = GraphConvBlock(64, 128, num_nodes)
        self.tcn2 = nn.Sequential(
            nn.Conv2d(128, embedding_dim, (9, 1), padding=(4, 0), bias=False),
            nn.BatchNorm2d(embedding_dim),
            nn.ReLU(inplace=True),
        )
        self.global_pool = nn.AdaptiveAvgPool2d(1)

    def forward(self, x):
        x = self.tcn1(self.gcn1(x))
        x = self.tcn2(self.gcn2(x))
        return self.global_pool(x).flatten(1)

class ExpectedGoalsModel:
    def __init__(self):
        self.coef = np.array([-0.115, 0.782, -0.240], dtype=np.float32)
        self.intercept = -0.450

    def compute_xg(self, distance, angle_radians, defender_density):
        features = np.asarray([distance, angle_radians, defender_density], dtype=np.float32)
        logit = features @ self.coef + self.intercept
        return 1.0 / (1.0 + np.exp(-logit))

class EloRatingSystem:
    def __init__(self, k_factor=32.0):
        self.k_factor = k_factor

    @staticmethod
    def predict_prob(rating_a, rating_b):
        return 1.0 / (1.0 + 10.0 ** ((rating_b - rating_a) / 400.0))

    def update_ratings(self, rating_a, rating_b, score_a):
        expected_a = self.predict_prob(rating_a, rating_b)
        delta = self.k_factor * (score_a - expected_a)
        return rating_a + delta, rating_b - delta

