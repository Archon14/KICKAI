def extract_stgcn_keypoints(df, img_dir, model, seq_len=30, batch_size=16):
    """Extract COCO-17 pose keypoints with batched YOLO inference.

    Output shape is (C=3, T, V=17, M), matching the original notebook.
    """
    frames = np.sort(df["frame"].unique())[:seq_len]
    frame_set = set(frames)

    seq_df = df[df["frame"].isin(frame_set)].copy()
    track_ids = seq_df["track_id"].drop_duplicates().to_numpy()
    track_to_idx = {tid: i for i, tid in enumerate(track_ids)}

    skeleton = np.zeros((3, len(frames), 17, len(track_ids)), dtype=np.float32)

    # groupby avoids repeatedly scanning the full dataframe for every frame
    grouped = seq_df.groupby("frame", sort=False)

    for t_idx, frame_id in enumerate(frames):
        img_path = os.path.join(img_dir, f"{int(frame_id):06d}.jpg")
        img = cv2.imread(img_path)
        if img is None:
            continue

        frame_rows = grouped.get_group(frame_id)
        crops, meta = [], []

        for row in frame_rows.itertuples(index=False):
            x1 = max(0, int(row.left))
            y1 = max(0, int(row.top))
            x2 = max(x1, x1 + int(row.width))
            y2 = max(y1, y1 + int(row.height))
            crop = img[y1:y2, x1:x2]
            if crop.size:
                crops.append(crop)
                meta.append((track_to_idx[row.track_id], x1, y1))

        # One GPU call per batch instead of one GPU call per player.
        for start in range(0, len(crops), batch_size):
            batch = crops[start:start + batch_size]
            batch_meta = meta[start:start + batch_size]
            results = model.predict(
                source=batch,
                device=DEVICE,
                verbose=False,
                batch=min(batch_size, len(batch)),
            )

            for result, (m_idx, x1, y1) in zip(results, batch_meta):
                if result.keypoints is None or len(result.keypoints.data) == 0:
                    continue

                kp = result.keypoints.data[0].detach().cpu().numpy()
                if kp.shape[0] != 17:
                    continue

                kp[:, 0] += x1
                kp[:, 1] += y1
                skeleton[:, t_idx, :, m_idx] = kp.T

    return torch.from_numpy(skeleton), track_ids

