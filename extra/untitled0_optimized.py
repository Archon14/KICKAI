import numpy as np

def compute_dtw_distance(user_seq, expert_seq):
    """DTW using vectorized frame-distance computation.

    Memory is O(N*M), but the expensive feature-distance calculation is
    performed by NumPy instead of Python loops.
    """
    user = np.asarray(user_seq, dtype=np.float32)
    expert = np.asarray(expert_seq, dtype=np.float32)
    N, M = len(user), len(expert)

    # Pairwise Euclidean frame distances: N x M
    dists = np.linalg.norm(user[:, None, :] - expert[None, :, :], axis=2)

    cost = np.full((N + 1, M + 1), np.inf, dtype=np.float32)
    cost[0, 0] = 0.0

    for i in range(1, N + 1):
        cost[i, 1:] = dists[i - 1] + np.minimum(
            np.minimum(cost[i - 1, 1:], cost[i, :-1]),
            cost[i - 1, :-1],
        )

    distance = float(cost[N, M])
    score = max(0.0, 100.0 - (distance / (N + M) * 10.0))
    return distance, score

def run_monte_carlo_simulation(home_xg_shots, away_xg_shots, iterations=10_000, seed=None):
    """Vectorized Monte Carlo simulation; same Bernoulli-per-shot model as before."""
    rng = np.random.default_rng(seed)
    home = np.asarray(home_xg_shots, dtype=np.float32)
    away = np.asarray(away_xg_shots, dtype=np.float32)

    home_goals = (
        rng.binomial(1, home, size=(iterations, home.size)).sum(axis=1)
        if home.size else np.zeros(iterations, dtype=np.int16)
    )
    away_goals = (
        rng.binomial(1, away, size=(iterations, away.size)).sum(axis=1)
        if away.size else np.zeros(iterations, dtype=np.int16)
    )

    return {
        "home_win_prob": float(np.mean(home_goals > away_goals)),
        "away_win_prob": float(np.mean(away_goals > home_goals)),
        "draw_prob": float(np.mean(home_goals == away_goals)),
        "expected_home_goals": float(home_goals.mean()),
        "expected_away_goals": float(away_goals.mean()),
        "variance_home": float(home_goals.var()),
        "variance_away": float(away_goals.var()),
    }

